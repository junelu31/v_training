// Offline loudness of every Drive clip. Writes drive-clip-levels.js.
// Uses ffmpeg's EBU R128 meter. Does not call xAI and does not rewrite mp3s.
import { spawn } from 'node:child_process';
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const voiceDir = path.join(root, 'public', 'voice');
const outFile = path.join(root, 'drive-clip-levels.js');

async function clipsIn(dir, prefix) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
    if (entry.isDirectory()) files.push(...await clipsIn(path.join(dir, entry.name), rel));
    else if (entry.name.endsWith('.mp3')) files.push(`voice/${rel}`);
  }
  return files;
}

function ffmpeg(file) {
  return new Promise((resolve, reject) => {
    const child = spawn('ffmpeg', [
      '-nostats', '-hide_banner', '-i', path.join(root, 'public', file),
      '-af', 'ebur128=peak=true,astats=metadata=1:reset=0',
      '-f', 'null', '-'
    ]);
    let text = '';
    child.stderr.on('data', chunk => { text += chunk; });
    child.on('error', reject);
    child.on('close', code => {
      if (code !== 0) reject(new Error(`ffmpeg ${code} ${file}`));
      else resolve(text);
    });
  });
}

function grab(text, pattern) {
  const match = text.match(pattern);
  return match ? Number(match[1]) : null;
}

async function measure(file) {
  const text = await ffmpeg(file);
  const summary = text.split('Summary:').pop();
  const lufs = grab(summary, /^\s*I:\s+(-?\d+(?:\.\d+)?)\s+LUFS/m);
  const truePeak = grab(summary, /^\s*Peak:\s+(-?\d+(?:\.\d+)?)\s+dBFS/m);
  const rms = grab(text, /RMS level dB:\s+(-?\d+(?:\.\d+)?)/);
  const samplePeak = grab(text, /Peak level dB:\s+(-?\d+(?:\.\d+)?)/);
  if (lufs == null || rms == null) throw new Error(`no level for ${file}`);
  return { file, lufs, truePeak: truePeak ?? samplePeak, rms };
}

function percentile(values, p) {
  const sorted = [...values].sort((a, b) => a - b);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.round((p / 100) * (sorted.length - 1))));
  return sorted[index];
}

const files = (await clipsIn(voiceDir, '')).sort();
const rows = [];
const queue = files.slice();
const workers = 16;
async function worker() {
  while (queue.length) {
    const file = queue.pop();
    rows.push(await measure(file));
    if (rows.length % 200 === 0) console.log(`measured ${rows.length}`);
  }
}
await Promise.all(Array.from({ length: workers }, worker));
rows.sort((a, b) => a.file.localeCompare(b.file));

const gated = rows.filter(row => row.lufs > -40);
const offset = gated.reduce((sum, row) => sum + (row.lufs - row.rms), 0) / gated.length;
const offsets = gated.map(row => row.lufs - row.rms).sort((a, b) => a - b);
const medianOffset = offsets[Math.floor(offsets.length / 2)];

const lines = rows.map(row => `  ${JSON.stringify(row.file)}: [${row.lufs.toFixed(2)}, ${row.truePeak.toFixed(2)}, ${row.rms.toFixed(2)}],`);
const before = gated.map(row => row.lufs);
const peaks = rows.map(row => row.truePeak);
const body = `// Generated by scripts/measure-clip-gains.mjs. Do not edit by hand.
// Each value is [integrated LUFS, true peak dBTP, RMS dBFS].
// LUFS at or under -40 is the EBU gate floor on a short clip; use RMS instead.

export const RMS_TO_LUFS_OFFSET = ${medianOffset.toFixed(3)};

export const LOUDNESS_BEFORE = {
  clips: ${rows.length},
  gated: ${gated.length},
  gateFloor: ${rows.length - gated.length},
  lufsMin: ${Math.min(...before).toFixed(2)},
  lufsP10: ${percentile(before, 10).toFixed(2)},
  lufsP50: ${percentile(before, 50).toFixed(2)},
  lufsP90: ${percentile(before, 90).toFixed(2)},
  lufsMax: ${Math.max(...before).toFixed(2)},
  peakMax: ${Math.max(...peaks).toFixed(2)}
};

export const CLIP_LEVELS = {
${lines.join('\n')}
};
`;
await writeFile(outFile, body);
console.log(`wrote ${rows.length} clips, offset ${medianOffset.toFixed(3)} (mean ${offset.toFixed(3)})`);
console.log('before', JSON.stringify({
  min: Math.min(...before),
  p50: percentile(before, 50),
  max: Math.max(...before),
  spread: Math.max(...before) - Math.min(...before),
  peakMax: Math.max(...peaks),
  gateFloor: rows.length - gated.length
}));
