// Prints every fixed Drive coach line as JSON for scripts/render_voice.py,
// or with --manifest writes drive-voice-clips.js from the clips that exist.
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { COACH_VOICE, PRACTICE_VOICE, clipFile, fixedVoiceLines, fragmentKey, fragmentLines, voiceKey } from '../drive-voice.js';

globalThis.window = {};
await import('../course.js');
const content = globalThis.window.COURSE_CONTENT;
const ids = new Set(content.drives.flatMap(drive => drive.lines));
const phrases = content.drills.filter(drill => ids.has(drill.id)).map(drill => drill.phrase).filter(Boolean);
const lines = [
  ...fixedVoiceLines(phrases).map(text => ({ text, key: voiceKey(text), file: clipFile(text) })),
  ...fragmentLines(phrases).map(text => ({ text, key: fragmentKey(text), file: clipFile(fragmentKey(text)), fragment: true }))
];

function manifestFor(voice) {
  const clips = {};
  let missing = 0;
  for (const line of lines) {
    const file = clipFile(line.fragment ? line.key : line.text, voice);
    if (existsSync(`public/${file}`)) clips[line.key] = file;
    else missing += 1;
  }
  return { clips, missing };
}

if (process.argv.includes('--manifest')) {
  const main = manifestFor(COACH_VOICE);
  const practice = manifestFor(PRACTICE_VOICE);
  await writeFile('drive-voice-clips.js', `// Generated by scripts/voice-lines.mjs --manifest. Do not edit.\nexport const VOICE_CLIPS = ${JSON.stringify(main.clips, null, 2)};\nexport const PRACTICE_CLIPS = ${JSON.stringify(practice.clips, null, 2)};\n`);
  console.log(`${Object.keys(main.clips).length} ${COACH_VOICE} clips, ${main.missing} missing. ${Object.keys(practice.clips).length} ${PRACTICE_VOICE} clips, ${practice.missing} missing.`);
} else {
  console.log(JSON.stringify(lines, null, 2));
}
