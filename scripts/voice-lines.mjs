// Prints every fixed Drive coach line as JSON.
// Coach lines (default) feed scripts/render_aurora_tts.mjs (xAI Aurora).
// Practice lines (VOICE=af_bella) feed scripts/render_voice.py (Kokoro).
// --manifest writes drive-voice-clips.js from the clips that exist.
import { existsSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { COACH_VOICE, PRACTICE_VOICE, clipFile, fixedVoiceLines, fragmentKey, fragmentLines, voiceKey } from '../drive-voice.js';

globalThis.window = {};
await import('../course.js');
const content = globalThis.window.COURSE_CONTENT;
const ids = new Set(content.drives.flatMap(drive => drive.lines));
const phrases = content.drills.filter(drill => ids.has(drill.id)).map(drill => drill.phrase).filter(Boolean);
function linesFor(voice) {
  return [
    ...fixedVoiceLines(phrases, voice).map(text => ({ text, key: voiceKey(text), file: clipFile(text, voice) })),
    ...fragmentLines(phrases).map(text => ({ text, key: fragmentKey(text), file: clipFile(fragmentKey(text), voice), fragment: true }))
  ];
}

const voice = process.env.VOICE || COACH_VOICE;

if (process.argv.includes('--manifest')) {
  const banks = [COACH_VOICE, PRACTICE_VOICE].map(id => {
    const lines = linesFor(id);
    const clips = Object.fromEntries(lines.filter(line => existsSync(`public/${line.file}`)).map(line => [line.key, line.file]));
    return { id, clips, missing: lines.length - Object.keys(clips).length };
  });
  const [coach, practice] = banks;
  await writeFile('drive-voice-clips.js', `// Generated by scripts/voice-lines.mjs --manifest. Do not edit.\nexport const VOICE_CLIPS = ${JSON.stringify(coach.clips, null, 2)};\nexport const PRACTICE_CLIPS = ${JSON.stringify(practice.clips, null, 2)};\n`);
  for (const bank of banks) console.log(`${bank.id}: ${Object.keys(bank.clips).length} clips, ${bank.missing} lines without a clip.`);
} else {
  console.log(JSON.stringify(linesFor(voice), null, 2));
}
